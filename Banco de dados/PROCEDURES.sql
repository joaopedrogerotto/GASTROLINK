CREATE OR ALTER PROCEDURE PR_S_PESQUISAR_PRATOS
	@NOME NVARCHAR(MAX) = NULL,
	@DESCRICAO NVARCHAR(MAX) = NULL,
	@PRECO DECIMAL(10,2) = NULL,
	@ID_CATEGORIA INT = NULL,
	@DISPONIBILIDAE BIT = NULL
AS
BEGIN
	SELECT 
		P.PRT_ID,
		P.PRT_NOME AS NOME,
		P.PRT_DESCRICAO AS DESCRICAO,
		P.PRT_PRECO AS PRECO,
		P.PRT_DISPONIBILIDADE AS DISPONIBILIDADE,
		P.PRT_TEMPO_MEDIO_PREPARO AS TEMPO,
		P.PRT_URL_IMAGEM as IMAGEM,
		CP.CTP_ID,
		CP.CTP_CATEGORIA AS CATEGORIA
	FROM TB_PRATOS P
	JOIN TB_CATEGORIAS_PRATO CP ON CP.CTP_ID = P.PRT_CAT_ID
	WHERE 
	(@NOME IS NULL OR P.PRT_NOME LIKE '%' + @NOME + '%')
	AND
	(@DESCRICAO IS NULL OR P.PRT_DESCRICAO LIKE '%' + @DESCRICAO + '%')
	AND
	(@PRECO IS NULL OR P.PRT_PRECO >= @PRECO)
	AND
	(@ID_CATEGORIA IS NULL OR CP.CTP_ID = @ID_CATEGORIA)
	AND
	(@DISPONIBILIDAE IS NULL OR P.PRT_DISPONIBILIDADE = @DISPONIBILIDAE)
END
GO

