CREATE OR ALTER PROCEDURE PR_I_PAGAMENTO
	@DESCONTO DECIMAL(10,2),
	@VALOR_TOTAL DECIMAL(10,2),
	@ID_PEDIDO INT,
	@PAGAMENTOS_JSON NVARCHAR(MAX),
	@ID_USUARIO INT
AS
BEGIN
	DECLARE @ID_MESA INT;

	SELECT @ID_MESA = PDD_MSA_ID FROM TB_PEDIDOS WHERE PDD_ID = @ID_PEDIDO

	INSERT INTO TB_PAGAMENTOS (
		PAG_DESCONTO, 
		PAG_VALOR_TOTAL, 
		PAG_VALOR_PAGO, 
		PAG_PDD_ID, 
		PAG_FPG_ID, 
		PAG_USU_ID, 
		PAG_DATA
	) SELECT 
		@DESCONTO, 
		@VALOR_TOTAL, 
		ValorPago, 
		@ID_PEDIDO, 
		IdFormaPagamento, 
		@ID_USUARIO, 
		GETDATE()
	FROM OPENJSON(@PAGAMENTOS_JSON)
	WITH(
		IdFormaPagamento INT '$.IdFormaPagamento',
		ValorPago DECIMAL (10,2) '$.ValorPago'
	);

	UPDATE TB_PEDIDOS
	SET PDD_STP_ID = 7
	WHERE PDD_ID = @ID_PEDIDO;

	UPDATE TB_MESAS
	SET MSA_STM_ID = 1
	WHERE MSA_ID = @ID_MESA
END
GO

CREATE OR ALTER PROCEDURE PR_S_DASHBOARD_CATEGORIAS
	@DATA_INICIO DATE = NULL,
	@DATA_FIM DATE = NULL
AS
BEGIN
	WITH CategoriasPedido AS(
		SELECT
			ITP.ITP_PDD_ID,
			CAP.CTP_ID,
			CAP.CTP_CATEGORIA,
			PDD.PDD_ID,
			SUM(ITP.ITP_QUANTIDADE * PRT.PRT_PRECO) AS VALOR_CATEGORIA,
			PDD.PDD_DATA
		FROM TB_ITENS_PEDIDO ITP
		INNER JOIN TB_PRATOS PRT ON PRT.PRT_ID = ITP.ITP_PRT_ID
		INNER JOIN TB_CATEGORIAS_PRATO CAP ON CAP.CTP_ID = PRT.PRT_CAT_ID
		INNER JOIN TB_PEDIDOS PDD ON PDD.PDD_ID= ITP.ITP_PDD_ID
		GROUP BY ITP.ITP_PDD_ID, CAP.CTP_ID, CAP.CTP_CATEGORIA,PDD.PDD_ID, PDD.PDD_DATA
	)
	SELECT  
		CTP_ID,
		CTP_CATEGORIA,
		SUM(VALOR_CATEGORIA) AS VALOR_VENDIDO
	FROM CategoriasPedido
	WHERE 
    (@DATA_INICIO IS NULL OR PDD_DATA >= @DATA_INICIO)
    AND
    (@DATA_FIM IS NULL OR PDD_DATA < DATEADD(DAY, 1, @DATA_FIM))
	GROUP BY CTP_ID,CTP_CATEGORIA;
END
GO

CREATE OR ALTER PROCEDURE PR_S_DASHBOARD_FORMA_PAGAMENTO
	@DATA_INICIO DATE = NULL,
	@DATA_FIM DATE = NULL
AS
BEGIN
	SELECT
		CAST(P.PAG_DATA AS DATE) AS DATA,
		FP.FPG_FORMA AS FORMA_PAGAMENTO,
		SUM(P.PAG_VALOR_PAGO) AS VALOR_TOTAL
	FROM TB_PAGAMENTOS P
	INNER JOIN TB_FORMAS_PAGAMENTO FP ON FP.FPG_ID = P.PAG_FPG_ID
	WHERE 
		(@DATA_INICIO IS NULL OR P.PAG_DATA >= @DATA_INICIO)
		AND
		(@DATA_FIM IS NULL OR P.PAG_DATA < DATEADD(DAY, 1, @DATA_FIM))
	GROUP BY
		CAST(P.PAG_DATA AS DATE),
		FP.FPG_FORMA
	ORDER BY
		DATA,
		FP.FPG_FORMA
END
GO

CREATE OR ALTER PROCEDURE PR_S_PRODUTOS_MAIS_VENDIDOS
AS
BEGIN
	SELECT TOP 5
		SUM(ITP.ITP_QUANTIDADE) AS QUANTIDADE,
		PRT.PRT_NOME AS NOME
	FROM TB_PAGAMENTOS PAG
	JOIN TB_PEDIDOS PED ON PAG.PAG_PDD_ID = PED.PDD_ID
	JOIN TB_ITENS_PEDIDO ITP ON ITP.ITP_PDD_ID = PED.PDD_ID
	JOIN TB_PRATOS PRT ON PRT.PRT_ID = ITP.ITP_PRT_ID
	GROUP BY PRT.PRT_NOME
	ORDER BY QUANTIDADE DESC;
END
GO

