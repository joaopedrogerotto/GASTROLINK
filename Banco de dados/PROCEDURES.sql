CREATE OR ALTER PROCEDURE PR_S_VALIDAR_LOGIN
	@LOGIN VARCHAR(150)

AS
BEGIN

	SELECT * FROM TB_USUARIOS USU
	JOIN TB_TIPOS_USUARIOS TPU ON TPU.TPU_ID = USU.USU_TPU_ID
	WHERE USU_LOGIN = @LOGIN AND USU_STATUS = 1
END
GO

