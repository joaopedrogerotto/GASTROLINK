CREATE OR ALTER PROCEDURE PR_I_PEDIDO
	@MESA_ID INT,
	@USUARIO_ID INT,
	@VALOR_TOTAL DECIMAL(10,2),
	@ITENS_PEDIDO ITENS_PEDIDOS_TYPE READONLY
AS
BEGIN
