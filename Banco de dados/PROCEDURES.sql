	@PEDIDO_ID INT
AS
BEGIN
	SELECT 
		P.PDD_ID AS NUMERO_PEDIDO,
		P.PDD_TOTAL AS TOTAL,
		P.PDD_DATA AS DATA,
		M.MSA_ID AS ID_MESA,
		M.MSA_NUMERO AS NUMERO_MESA,
		PRT.PRT_ID AS ID_PRATO,
		PRT.PRT_NOME AS NOME_PRATO,
		PRT.PRT_PRECO AS PRECO,
		PRT.PRT_URL_IMAGEM AS IMAGEM,
		PRT.PRT_DESCRICAO AS DESCRICAO,
		PRT.PRT_TEMPO_MEDIO_PREPARO AS TEMPO_MEDIO,
