CREATE OR ALTER PROCEDURE PR_S_QTD_PRATOS_CATEGORIA
AS
BEGIN
	SELECT
		CP.CTP_ID,
		CP.CTP_CATEGORIA,
		COUNT(P.PRT_ID) AS QTD_PRATOS
	FROM TB_CATEGORIAS_PRATO CP
	LEFT JOIN TB_PRATOS P ON CP.CTP_ID = P.PRT_CAT_ID
	GROUP BY
		CP.CTP_ID,
		CP.CTP_CATEGORIA;
END
GO

